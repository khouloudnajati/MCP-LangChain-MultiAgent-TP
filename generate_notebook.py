        "    if b == 0:\n",
        "        error_msg = \"Error: Division by zero is not allowed.\"\n",
        "        print(f\"[math_server] divide({a}, {b}) = {error_msg}\", file=sys.stderr)\n",
        "        return error_msg\n",
        "    result = a / b\n",
        "    print(f\"[math_server] divide({a}, {b}) = {result}\", file=sys.stderr)\n",
        "    return result\n",
